# ============================================================
# hypothesis_tests.R
# Проверка статистических гипотез для Главы 3.2 отчета
# ============================================================
suppressPackageStartupMessages({
  library(readr)
  library(dplyr)
})

BASE_DIR <- "C:/Users/rewhe/Desktop/videonabludenie"
# Загружаем исходные данные (или можно загрузить df_clean)
df <- read_csv(file.path(BASE_DIR, "data", "cases_features.csv"), show_col_types = FALSE)

# Базовая фильтрация (как в других скриптах)
df <- df %>%
  filter(
    !is.na(case_type),
    !is.na(duration), duration > 0, duration < 365
  )

# ============================================================
# ГИПОТЕЗА 1: Различается ли частота отсутствия камер по округам?
# ============================================================
cat("\n======================================================\n")
cat("ГИПОТЕЗА 1: Зависит ли отсутствие камер (pat_absence_camera) от региона?\n")
cat("H0: Признак pat_absence_camera не зависит от федерального округа (распределения одинаковы).\n")
cat("H1: Признак pat_absence_camera зависит от федерального округа (распределения различаются).\n")
cat("Метод: Критерий хи-квадрат Пирсона (Chi-squared test)\n")
cat("======================================================\n")

# Создаем таблицу сопряженности (Contingency table)
table_h1 <- table(df$district, df$pat_absence_camera)
print(table_h1)

# Запускаем тест
test_h1 <- chisq.test(table_h1)
print(test_h1)

# Вывод для отчета
p_val_h1 <- test_h1$p.value
if(p_val_h1 < 0.05) {
  cat(sprintf("\nВЫВОД: p-value = %.4f < 0.05. Отвергаем H0. \nЧастота отсутствия камер статистически значимо различается по округам.\n", p_val_h1))
} else {
  cat(sprintf("\nВЫВОД: p-value = %.4f >= 0.05. Нет оснований отвергнуть H0. \nРазличия по округам статистически не значимы.\n", p_val_h1))
}


# ============================================================
# ГИПОТЕЗА 2: Влияет ли использование камер как доказательства на срок дела?
# ============================================================
cat("\n======================================================\n")
cat("ГИПОТЕЗА 2: Различается ли длительность суда при использовании видео как доказательства?\n")
cat("H0: Медиана длительности дел с pat_evidence равна медиане длительности дел без него.\n")
cat("H1: Медиана длительности дел с pat_evidence отличается.\n")
cat("Метод: U-критерий Манна-Уитни (Wilcoxon rank sum test)\n")
cat("======================================================\n")

# Смотрим медианы для контекста
medians <- df %>%
  group_by(pat_evidence) %>%
  summarise(
    n_cases = n(),
    median_duration = median(duration, na.rm = TRUE),
    mean_duration = mean(duration, na.rm = TRUE)
  )
print(medians)

# Запускаем тест Манна-Уитни (так как данные о длительности скошены и не нормальны)
test_h2 <- wilcox.test(duration ~ pat_evidence, data = df)
print(test_h2)

# Вывод для отчета
p_val_h2 <- test_h2$p.value
if(p_val_h2 < 0.05) {
  cat(sprintf("\nВЫВОД: p-value = %.4f < 0.05. Отвергаем H0. \nДлительность рассмотрения дел статистически значимо различается в зависимости от использования видеозаписей как доказательств.\n", p_val_h2))
} else {
  cat(sprintf("\nВЫВОД: p-value = %.4f >= 0.05. Нет оснований отвергнуть H0. \nСтатистически значимых различий в длительности не обнаружено.\n", p_val_h2))
}