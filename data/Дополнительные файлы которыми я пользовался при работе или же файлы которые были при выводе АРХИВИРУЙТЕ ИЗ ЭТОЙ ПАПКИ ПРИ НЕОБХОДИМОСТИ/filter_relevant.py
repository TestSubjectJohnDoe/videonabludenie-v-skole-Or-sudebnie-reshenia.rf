def extract_text(soup):
    """Извлечь весь текст страницы, убрав скрипты, стили и служебные блоки."""
    for tag in soup(["script", "style", "header", "footer", "nav"]):
        tag.decompose()
    return soup.get_text(separator=" ")

# ---------- Сбор файлов ----------
html_files = []
for root, dirs, files in os.walk(BASE_DIR):
    if "_Videonablyudenie_v_skole" in root:
        for f in files:
            if f.endswith(".html"):
                html_files.append(os.path.join(root, f))

print(f"Найдено HTML-файлов: {len(html_files)}")
if not html_files:
    sys.exit(0)

# ---------- Фильтрация ----------
relevant = []
for path in html_files:
    try:
        with open(path, "r", encoding="utf-8") as f:
            soup = BeautifulSoup(f, "lxml")
    except:
        continue
    text = extract_text(soup)
    text_lower = text.lower()
    matched = [desc for pat, desc in KEY_PATTERNS if re.search(pat, text_lower)]
    if matched:
        district = "unknown"
        parts = Path(path).parts
        for p in parts:
            if "_Videonablyudenie_v_skole" in p:
                district = p.replace("_Videonablyudenie_v_skole", "")
                break
        cid = Path(path).stem
        relevant.append((cid, district, path, "; ".join(matched)))

print(f"Релевантных дел: {len(relevant)}")
with open(OUTPUT_CSV, "w", encoding="utf-8-sig", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(["ID", "Округ", "Путь к файлу", "Паттерны"])
    writer.writerows(relevant)
print(f"Список сохранён в {OUTPUT_CSV}")